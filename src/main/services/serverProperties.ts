import path from 'node:path'
import { promises as fs } from 'node:fs'
import { BEDROCK_PROPERTY_DEFAULTS, SERVER_PROPERTY_DEFAULTS } from '@shared/serverProperties'
import { ensureDir } from '../util/fs'

export function unescapeProperty(value: string): string {
  let output = ''
  for (let index = 0; index < value.length; index += 1) {
    const char = value[index]!
    if (char !== '\\' || index + 1 >= value.length) {
      output += char
      continue
    }
    const next = value[index + 1]!
    index += 1
    switch (next) {
      case 'n':
        output += '\n'
        break
      case 'r':
        output += '\r'
        break
      case 't':
        output += '\t'
        break
      case 'u': {
        const hex = value.slice(index + 1, index + 5)
        if (/^[0-9a-fA-F]{4}$/.test(hex)) {
          output += String.fromCharCode(Number.parseInt(hex, 16))
          index += 4
        } else {
          output += 'u'
        }
        break
      }
      default:
        output += next
    }
  }
  return output
}

export function escapeProperty(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/:/g, '\\:')
    .replace(/=/g, '\\=')
}

function splitProperty(line: string): [string, string] | null {
  let escaped = false
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index]!
    if (!escaped && (char === '=' || char === ':')) {
      return [line.slice(0, index), line.slice(index + 1)]
    }
    escaped = !escaped && char === '\\'
    if (char !== '\\') escaped = false
  }
  if (escaped) return null
  return [line, '']
}

export function parseProperties(text: string): Map<string, string> {
  const map = new Map<string, string>()
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#') || line.startsWith('!')) continue
    const parts = splitProperty(line)
    if (!parts) continue
    const key = unescapeProperty(parts[0].trim())
    if (key) map.set(key, unescapeProperty(parts[1].trim()))
  }
  return map
}

export function formatProperties(properties: Map<string, string>): string {
  const lines = [...properties.entries()].map(
    ([key, value]) => `${escapeProperty(key)}=${escapeProperty(value)}`
  )
  return `${lines.join('\n')}\n`
}

export function defaultProperties(
  overrides: Record<string, string> = {},
  base: Record<string, string> = SERVER_PROPERTY_DEFAULTS
): Map<string, string> {
  return new Map(Object.entries({ ...base, ...overrides }))
}

export async function readProperties(
  serverDir: string,
  defaults: Record<string, string> = SERVER_PROPERTY_DEFAULTS
): Promise<Map<string, string>> {
  const file = path.join(serverDir, 'server.properties')
  try {
    const text = await fs.readFile(file, 'utf8')
    return new Map([...defaultProperties({}, defaults), ...parseProperties(text)])
  } catch {
    return defaultProperties({}, defaults)
  }
}

export async function writeProperties(
  serverDir: string,
  properties: Map<string, string>
): Promise<void> {
  await ensureDir(serverDir)
  await fs.writeFile(path.join(serverDir, 'server.properties'), formatProperties(properties), 'utf8')
}

export async function patchProperties(
  serverDir: string,
  patch: Record<string, string>
): Promise<Map<string, string>> {
  const current = await readProperties(serverDir)
  for (const [key, value] of Object.entries(patch)) {
    if (typeof value !== 'string') continue
    current.set(key, value)
  }
  await writeProperties(serverDir, current)
  return current
}

export async function levelName(
  serverDir: string,
  defaults: Record<string, string> = SERVER_PROPERTY_DEFAULTS
): Promise<string> {
  const properties = await readProperties(serverDir, defaults)
  const name = properties.get('level-name')?.trim()
  return name && !name.includes('..') && !/[\\/:*?"<>|]/.test(name) ? name : 'world'
}

export async function ensureEula(serverDir: string, accepted: boolean): Promise<void> {
  if (!accepted) return
  const file = path.join(serverDir, 'eula.txt')
  await fs.writeFile(
    file,
    `# Generated by Newbie Launcher after the user accepted the Minecraft EULA.\neula=true\n`,
    'utf8'
  )
}
